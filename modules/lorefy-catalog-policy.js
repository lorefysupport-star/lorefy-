(function (root) {
  'use strict';

  function normalized(value) {
    return String(value || '')
      .normalize('NFKD')
      .replace(/[\u0300-\u036f\u064b-\u065f\u0670]/g, '')
      .replace(/[أإآ]/g, 'ا')
      .replace(/ؤ/g, 'و')
      .replace(/ئ/g, 'ي')
      .toLowerCase()
      .replace(/[^a-z0-9\u0600-\u06ff]+/g, ' ')
      .replace(/\s+/g, ' ')
      .trim();
  }

  function isExcludedTitle(value) {
    var title = normalized(value);
    if (!title) return false;
    if (/(?:^| )(?:tarot|تاروت)(?: |$)/.test(title)) return true;
    if (/^(?:(?:the|holy|noble|al) )*(?:quran|qur an|koran|قران|القران|مصحف|المصحف)(?: |$)/.test(title)) return true;
    if (/^(?:(?:the|holy) )*(?:bible|الانجيل|انجيل|الكتاب المقدس)(?: |$)/.test(title)) {
      return !/^(?:the )?bible of /.test(title);
    }
    return false;
  }

  function isExcludedWork(work) {
    var retailerAccessory = work && /^jarir-/i.test(String(work.id || '')) &&
      [].concat(work.genres || []).some(function (genre) { return normalized(genre) === 'فواصل الكتب'; });
    return Boolean(work && (retailerAccessory || isExcludedTitle(work.title) || isExcludedTitle(work.ar)));
  }

  function isExplicitWork(work) {
    if (!work) return false;
    if (work.isAdult === true || work.adult === true) return true;
    if (/^(?:erotica|pornographic|explicit|r18|r18\+)$/.test(String(work.contentRating || '').toLowerCase())) return true;
    var labels = [].concat(work.genres || [], work.tags || []);
    return labels.some(function(label){
      var name = typeof label === 'object' && label ? label.name || label.label : label;
      return /(?:^| )(?:hentai|erotica|erotic fiction|pornographic|pornography|smut|هنتاي|اباحي)(?: |$)/.test(normalized(name));
    });
  }

  function isAiGeneratedWork(work) {
    if (!work) return false;
    if (work.aiGenerated === true || work.isAiGenerated === true || work.authorship === 'ai-generated') return true;
    return [].concat(work.genres || [], work.tags || []).some(function(label){
      var name = typeof label === 'object' && label ? label.name || label.label : label;
      return /^(?:ai generated|ai authored|generated by ai|chatgpt generated|written by chatgpt)$/.test(normalized(name));
    });
  }

  var eligibilityCache = new WeakMap();
  function isRecommendationEligible(work) {
    if (!work || typeof work !== 'object') return false;
    var signature = JSON.stringify([work.id,work.title,work.ar,work.isAdult,work.adult,work.contentRating,
      work.aiGenerated,work.isAiGenerated,work.authorship,work.genres,work.tags,work.r,work.rSrc]);
    var cached = eligibilityCache.get(work);
    if (cached && cached.signature === signature) return cached.eligible;
    var eligible = computeRecommendationEligibility(work);
    eligibilityCache.set(work,{signature:signature,eligible:eligible,discovery:computeRecommendationEligibility(work,true)});
    return eligible;
  }

  function isDiscoveryEligible(work) {
    if (!work || typeof work !== 'object') return false;
    isRecommendationEligible(work);
    return eligibilityCache.get(work).discovery;
  }

  function computeRecommendationEligibility(work, allowUnrated) {
    if (!work || isExcludedWork(work) || isExplicitWork(work) || isAiGeneratedWork(work)) return false;
    var rating = Number(work.r);
    if (!allowUnrated && (!Number.isFinite(rating) || rating <= 0 || rating > 5)) return false;
    if (!allowUnrated && /^fwn-novel-/i.test(String(work.id || '')) && !String(work.rSrc || '').trim()) return false;
    // Popularity and ratings are not evidence of a content classification.
    var knownMal = [1,2,3,11,12,13,21,26,23390,44347,56805,96792];
    var knownAniList = [30001,30002,30003,30011,30012,30013,30021,30026,53390,74347,85135,87216];
    // AniList isAdult values verified by ID on 2026-10-03. Do not infer a
    // classification for unrelated records merely from their source label.
    var id = String(work.id || '');
    var mal = /^mal-manga-(\d+)(?:-|$)/.exec(id);
    var ani = /^(?:api-)?anilist-(\d+)(?:-|$)/.exec(id);
    var verified = mal && knownMal.indexOf(Number(mal[1])) !== -1 || ani && knownAniList.indexOf(Number(ani[1])) !== -1;
    return work.isAdult === false || /^(?:safe|suggestive)$/.test(String(work.contentRating || '').toLowerCase()) || Boolean(verified);
  }

  function filterInPlace(works) {
    if (!Array.isArray(works)) return works;
    for (var index = works.length - 1; index >= 0; index -= 1) {
      if (isExcludedWork(works[index]) || isExplicitWork(works[index]) || isAiGeneratedWork(works[index])) works.splice(index, 1);
    }
    return works;
  }

  var policy = { isExcludedTitle: isExcludedTitle, isExcludedWork: isExcludedWork, isExplicitWork:isExplicitWork, isAiGeneratedWork:isAiGeneratedWork, isRecommendationEligible:isRecommendationEligible, isDiscoveryEligible:isDiscoveryEligible, filterInPlace: filterInPlace };
  root.LorefyCatalogPolicy = policy;
  if (typeof module !== 'undefined' && module.exports) module.exports = policy;
})(typeof window !== 'undefined' ? window : globalThis);
