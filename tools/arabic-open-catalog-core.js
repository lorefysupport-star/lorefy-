'use strict';
const identity=require('../modules/lorefy-catalog-identity');
const policy=require('../modules/lorefy-catalog-policy');
const {parse}=require('csv-parse/sync');
const ARABIC=/[\u0600-\u06ff]/;
const clean=value=>String(value||'').replace(/\s+/g,' ').trim();
const unique=values=>[...new Set(values.map(clean).filter(Boolean))];
const value=(row,key)=>clean(row[key]?.value);
const entity=text=>/^https?:\/\/www\.wikidata\.org\/entity\/(Q[1-9]\d*)$/.exec(text)?.[1]||'';
const split=value=>unique(String(value||'').split(' :: '));
const authorKey=text=>identity.normalizeText(text).split(' ').filter(Boolean).sort().join(' ');
function parseOpeniti(text) {
  return parse(text,{delimiter:'\t',columns:true,quote:null,bom:true,skip_empty_lines:true});
}
function assertCompleteSource(rows,limit) {
  if(!Array.isArray(rows)||!rows.length)throw new Error('Arabic metadata source is empty; catalog not changed.');
  if(rows.length>=limit)throw new Error('Arabic metadata source reached its query limit; catalog not changed.');
}
function allowed(work) {
  return !policy.isExcludedWork(work)&&!policy.isExplicitWork(work)&&!policy.isAiGeneratedWork(work)
    &&!/(?:ai[- ]generated|generated by ai|written by chatgpt|مولد بالذكاء الاصطناعي)/i.test(work.title);
}
function kinds(labels) {
  if(labels.some(x=>/film|television|journal|article|video game|comic|manga|manhwa|manhua|book edition/i.test(x)))return null;
  if(labels.some(x=>/\bnovel\b/i.test(x)))return {type:'رواية',genres:['Fiction']};
  if(labels.some(x=>/short stor(?:y|ies)|story collection/i.test(x)))return {type:'كتاب',genres:['Short Stories']};
  if(labels.some(x=>/poetry|poem/i.test(x)))return {type:'كتاب',genres:['Poetry']};
  if(labels.some(x=>/\bplay\b|drama/i.test(x)))return {type:'كتاب',genres:['Drama']};
  if(labels.some(x=>/biograph|memoir/i.test(x)))return {type:'كتاب',genres:['Biography']};
  if(labels.some(x=>/book|literary work|essay|encyclop/i.test(x)))return {type:'كتاب',genres:['Literature']};
  return null;
}
function base(id,title,auth,type,genres,source,provenance) {
  return {id,title,ar:title,auth,type,genres:unique([...genres,'Arabic']),language:'ar',tags:['عربي'],
    source,pl:source,provenance,r:0,rSrc:'',pop:0,baseRatings:0,baseReviews:0,weeklyReads:0,listAdds:0,
    yr:0,sourceCoverUrl:'',cover:'',synopsis:'',sc:{},ch:0,vol:0,pages:0};
}
function mapWikidata(rows) {
  const groups=new Map();
  for(const row of rows||[]) {
    const id=entity(value(row,'work'));
    const author=entity(value(row,'author'));
    if(!id||!author||!ARABIC.test(value(row,'workLabel'))||!ARABIC.test(value(row,'authorLabel')))continue;
    if(!groups.has(id))groups.set(id,[]);
    groups.get(id).push(row);
  }
  const works=[];
  for(const [id,group] of groups) {
    const classification=kinds(unique(group.flatMap(r=>[value(r,'kindLabel'),value(r,'formLabel')])));
    if(!classification)continue;
    const years=group.map(r=>/^([12]\d{3})-/.exec(value(r,'date'))?.[1]).filter(Boolean).map(Number);
    const year=years.length?Math.min(...years):0;
    if(!year||year>2021)continue;
    const authors=new Map();
    for(const r of group)authors.set(entity(value(r,'author')),value(r,'authorLabel'));
    const originalTitle=value(group[0],'workLabel');
    const title=originalTitle.replace(/\s*\((?:رواية|كتاب|مسرحية|مجموعة قصصية|ديوان شعر)\)\s*$/,'').trim();
    const genres=unique([...classification.genres,...group.map(r=>value(r,'genreLabel'))]);
    const w=base('wikidata-'+id,title,[...authors.values()].join('، '),classification.type,genres,'Wikidata',
      {url:'https://www.wikidata.org/wiki/'+id,method:'arabic-structured-catalog',license:'CC0-1.0',
        publicationCutoff:2021,aiScreening:'declared-metadata-and-pre-2022-cutoff-not-authorship-certification'});
    w.wikidataId=id;w.yr=year;
    w.altTitles=unique([originalTitle,...group.map(r=>value(r,'workEn'))].filter(t=>t!==title));
    w.authorAliases=unique(group.map(r=>value(r,'authorEn')));
    const ol=unique(group.map(r=>value(r,'ol'))).filter(x=>/^OL\d+W$/.test(x));
    if(ol.length===1)w.openLibraryId=ol[0];
    // Multiple Open Library work IDs are retained for review, not silently merged.
    w.provenance.openLibraryWorkIds=ol;
    w._apiSource='Wikidata';w._apiSourceId=id;
    if(allowed(w))works.push(w);
  }
  return works;
}
function openitiGenres(tags) {
  const n=identity.normalizeText(tags);
  const mapping={Poetry:/شعر|دواوين|poetry|shicr/,History:/تاريخ|history|tarikh|akhbar/,
    Biography:/تراجم|طبقات|سير|biograph|tarajim/,Geography:/جغراف|جغرافي|geograph|jughr/,
    Travel:/رحلات|رحلة|travel|rihla/,Philosophy:/فلسف|philosoph/,
    Science:/علمية|science/,Medicine:/(?:^| )(?:الطب|الطبية|medicine|tibb)(?: |$)/,
    Linguistics:/نحو|لغة|بلاغة|لغوية|linguist|nahw|lugha/,
    Religion:/فقه|تفسير|حديث|عقيدة|أصول|اصول|quran|hadith|fiqh|tafsir/};
  const found=Object.keys(mapping).filter(key=>mapping[key].test(n));
  return found.length?found:['Literature'];
}
function mapOpeniti(rows) {
  const works=new Map();
  for(const row of rows||[]) {
    const uri=clean(row.version_uri);
    if(!/^[A-Za-z0-9]+\.[A-Za-z0-9]+\..+-ara\d+$/.test(uri))continue;
    const titles=split(row.title_ar),authors=split(row.author_ar);
    if(!titles.length||!authors.length||!titles.every(t=>ARABIC.test(t))||!authors.every(a=>ARABIC.test(a)))continue;
    if(authors.some(a=>/^(?:مجهول|لا ينطبق|غير معروف)$/.test(a)))continue;
    const workUri=uri.split('.').slice(0,2).join('.');
    if(works.has(workUri)) {
      const w=works.get(workUri);
      w.altTitles=unique([...w.altTitles,...titles.filter(t=>t!==w.title),...split(row.title_lat)]);
      w.authorAliases=unique([...w.authorAliases,...authors.filter(a=>a!==w.auth),...split(row.author_lat)]);
      w.genres=unique([...w.genres,...openitiGenres(row.tags)]);
      continue;
    }
    const w=base('openiti-'+workUri,titles[0],authors[0],'كتاب',openitiGenres(row.tags),'OpenITI / KITAB',
      {url:'https://github.com/OpenITI/release/tree/master/data/'+workUri.split('.')[0]+'/'+workUri,
        method:'official-openiti-kitab-metadata',license:'CC-BY-NC-SA-4.0',release:'2023.1.8',
        authorDeathYearAH:Number(row.date)||0,aiScreening:'premodern-corpus-metadata-not-full-text-certification'});
    w.altTitles=unique([...titles.slice(1),...split(row.title_lat)]);
    w.authorAliases=unique([...authors.slice(1),...split(row.author_lat)]);w._apiSource='OpenITI';w._apiSourceId=workUri;
    // Date is the author's death year in AH; thumbnail is a text-reuse graph.
    // Neither is a publication year or a book cover.
    if(allowed(w))works.set(workUri,w);
  }
  return [...works.values()];
}
function openLibraryId(w) {
  for(const x of [w.openLibraryId,w.olid,w._apiSourceId,String(w.id||'').replace(/^ol-(?:works-|ar-)?/i,'')]) {
    if(/^OL\d+W$/i.test(String(x||'')))return String(x).toUpperCase();
  }
  return '';
}
function reconcile(existing,candidates) {
  const byId=new Map(),byOL=new Map(),byTitle=new Map();
  const index=w=>{
    byId.set(w.id,w);
    const ol=openLibraryId(w);if(ol){if(!byOL.has(ol))byOL.set(ol,[]);byOL.get(ol).push(w);}
    for(const title of unique([w.title,w.ar,...w.altTitles||[]])) {
      const key=identity.canonicalWorkKey(title);
      if(!byTitle.has(key))byTitle.set(key,[]);byTitle.get(key).push(w);
    }
  };
  existing.forEach(index);
  const additions=[];let enriched=0;
  for(const c of candidates) {
    const exact=byId.get(c.id);
    const ol=openLibraryId(c);
    const possibilities=unique([c.title,...c.altTitles||[]]).flatMap(t=>byTitle.get(identity.canonicalWorkKey(t))||[]);
    const target=exact||(ol?byOL.get(ol)||[]:[]).find(w=>w.type===c.type)||possibilities.find(w=>
      w.type===c.type&&unique([w.auth,...w.authorAliases||[]]).some(a=>unique([c.auth,...c.authorAliases||[]]).some(b=>authorKey(a)===authorKey(b))));
    if(!target){additions.push(c);index(c);continue;}
    const previous=JSON.stringify([target.title,target.auth,target.type,target.genres,target.altTitles,target.authorAliases,target.language,target.provenance]);
    if(exact&&/^(?:wikidata-Q\d+|openiti-.+)$/.test(c.id)) {
      target.altTitles=unique([...target.altTitles||[],target.title]);
      target.title=c.title;target.ar=c.title;target.type=c.type;target.genres=c.genres;target.auth=c.auth;
    }
    target.altTitles=unique([...target.altTitles||[],c.title,...c.altTitles||[]]).filter(t=>t!==target.title);
    target.authorAliases=unique([...target.authorAliases||[],c.auth,...c.authorAliases||[]]).filter(a=>a!==target.auth);
    if(!target.language)target.language=c.language;
    target.provenance={...target.provenance,arabicMetadataSources:unique([...target.provenance?.arabicMetadataSources||[],c.provenance?.url])};
    if(previous!==JSON.stringify([target.title,target.auth,target.type,target.genres,target.altTitles,target.authorAliases,target.language,target.provenance])) {
      enriched++;delete target._queryIndex;target._indexed=false;
    }
  }
  return {additions,enriched};
}
