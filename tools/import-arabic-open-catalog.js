'use strict';
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const {execFileSync}=require('node:child_process');
const {extractCatalogRecords}=require('../modules/lorefy-catalog-data');
const {acquireCatalogLock}=require('./catalog-import-lock');
const {mapWikidata,mapOpeniti,parseOpeniti,reconcile,assertCompleteSource}=require('./arabic-open-catalog-core');
const root=path.resolve(__dirname,'..');
const cache=path.join(root,'output/catalog-bulk/arabic-open');
const uploads=path.join(root,'uploads');
const query=`SELECT ?work ?workLabel ?workEn ?author ?authorLabel ?authorEn ?kindLabel ?formLabel ?date ?ol ?genreLabel WHERE {
  ?work wdt:P407 wd:Q13955; wdt:P50 ?author; wdt:P31 ?kind; wdt:P577 ?date; rdfs:label ?workLabel.
  FILTER(LANG(?workLabel)="ar") FILTER(YEAR(?date)<=2021)
  ?author wdt:P31 wd:Q5; rdfs:label ?authorLabel. FILTER(LANG(?authorLabel)="ar")
  ?kind rdfs:label ?kindLabel. FILTER(LANG(?kindLabel)="en")
  FILTER(REGEX(?kindLabel,"book|novel|literary work|story collection|poetry collection|play|essay","i"))
  OPTIONAL {?work rdfs:label ?workEn. FILTER(LANG(?workEn)="en")}
  OPTIONAL {?author rdfs:label ?authorEn. FILTER(LANG(?authorEn)="en")}
  OPTIONAL {?work wdt:P648 ?ol}
  OPTIONAL {?work wdt:P136 ?genre. ?genre rdfs:label ?genreLabel. FILTER(LANG(?genreLabel)="en")}
  OPTIONAL {?work wdt:P7937 ?form. ?form rdfs:label ?formLabel. FILTER(LANG(?formLabel)="en")}
} LIMIT 20000`;
const SOURCES={
  wikidata:{url:'https://query.wikidata.org/sparql?format=json&query='+encodeURIComponent(query),file:'wikidata-forms-v2.json'},
  openiti:{url:'https://raw.githubusercontent.com/kitab-project-org/kitab_metadata_for_DLME/main/kitab_metadata_for_DLME_latest_release.tsv',file:'openiti.tsv'}
};
async function readSource(source) {
  const file=path.join(cache,source.file);
  if(fs.existsSync(file)&&process.env.LOREFY_ARABIC_REFRESH!=='1')return fs.readFileSync(file,'utf8');
  const response=await fetch(source.url,{headers:{Accept:source.file.endsWith('.json')?'application/sparql-results+json':'text/plain','User-Agent':'LorefyArabicCatalog/1.0'},signal:AbortSignal.timeout(120000)});
  if(!response.ok)throw new Error(`Arabic source ${source.file}: HTTP ${response.status}`);
  const content=await response.text();
  if(source.file.endsWith('.json'))JSON.parse(content);
  fs.mkdirSync(cache,{recursive:true});fs.writeFileSync(file,content);
  return content;
}
async function main() {
  const rows=JSON.parse(await readSource(SOURCES.wikidata)).results.bindings;
  const historic=parseOpeniti(await readSource(SOURCES.openiti));
  assertCompleteSource(rows,20000);
  assertCompleteSource(historic,Number.POSITIVE_INFINITY);
  const wikidata=mapWikidata(rows),openiti=mapOpeniti(historic);
  const sourceDir=path.join(uploads,'catalog-sources');fs.mkdirSync(sourceDir,{recursive:true});
  // Redistributable metadata exports retain each source's separate license.
  fs.writeFileSync(path.join(sourceDir,'wikidata-arabic.json'),JSON.stringify({source:'Wikidata',license:'CC0-1.0',sourceUrl:'https://www.wikidata.org/wiki/Wikidata:Licensing',records:wikidata}));
  fs.writeFileSync(path.join(sourceDir,'openiti-arabic.json'),JSON.stringify({source:'OpenITI / KITAB',release:'2023.1.8',license:'CC-BY-NC-SA-4.0',licenseUrl:'https://creativecommons.org/licenses/by-nc-sa/4.0/',sourceUrl:'https://github.com/kitab-project-org/kitab_metadata_for_DLME',modifications:'Arabic bibliographic metadata only; duplicate text editions merged; no full text, reuse graphs, or inferred publication years.',records:openiti}));
  const release=await acquireCatalogLock(root);
  try {
    const files=fs.readdirSync(uploads).filter(n=>/^lorefy-data-part\d+\.js$/.test(n));
    const shards=files.map(file=>({file,text:fs.readFileSync(path.join(uploads,file),'utf8')}));
    const currentWikidataIds=new Set(wikidata.map(w=>w.id));
    let retiredSourceRows=0;
    for(const shard of shards){
      shard.records=extractCatalogRecords(shard.text);shard.previous=JSON.stringify(shard.records);
      // Only this importer's generated source rows can be withdrawn; no user data or other sources.
      shard.records=shard.records.filter(w=>{
        const retire=/^wikidata-Q\d+$/.test(w.id)&&w.provenance?.method==='arabic-structured-catalog'&&!currentWikidataIds.has(w.id);
        if(retire)retiredSourceRows++;return !retire;
      });
    }
    const existing=shards.flatMap(s=>s.records);
    // Editorial extensions participate in identity lookup but remain generated by their own tools.
    const scope={window:{LorefyMangaData:[]}};
    vm.runInNewContext(fs.readFileSync(path.join(uploads,'lorefy-arabic-library.js'),'utf8'),scope);
    const existingIds=new Set(existing.map(w=>w.id));
    const extension=scope.window.LorefyMangaData.filter(w=>!existingIds.has(w.id));
    const result=reconcile(existing.concat(extension),[...wikidata,...openiti]);
    const changed=[];
    for(const shard of shards) {
      if(shard.previous===JSON.stringify(shard.records))continue;
      const marker='Array.prototype.push.apply(window.LorefyMangaData,';
      const start=shard.text.indexOf(marker);
      if(start<0)throw new Error(`Unexpected shard wrapper: ${shard.file}`);
      fs.writeFileSync(path.join(uploads,shard.file),shard.text.slice(0,start+marker.length)+JSON.stringify(shard.records)+');\n');
      changed.push(shard.file);
    }
    // Keep updates to generated editorial anchors as retained dynamic records.
    const retained=extension.filter(w=>w.provenance?.arabicMetadataSources?.length);
    const additions=result.additions.concat(retained);
    let next=Math.max(...files.map(f=>Number(/part(\d+)/.exec(f)[1])))+1;
    const installed=[];
    for(let offset=0;offset<additions.length;offset+=500) {
      const file='lorefy-data-part'+String(next++).padStart(2,'0')+'.js';
      fs.writeFileSync(path.join(uploads,file),'/* Arabic bibliographic metadata: Wikidata CC0; OpenITI/KITAB CC-BY-NC-SA 4.0; licenses in catalog-sources. No full texts. */\nwindow.LorefyMangaData=window.LorefyMangaData||[];\nArray.prototype.push.apply(window.LorefyMangaData,'+JSON.stringify(additions.slice(offset,offset+500))+');\n');
      installed.push(file);
    }
    execFileSync(process.execPath,[path.join(root,'tools/build-catalog-map.js')],{stdio:'inherit'});
    const report={generatedAt:new Date().toISOString(),wikidataRows:rows.length,wikidataLimitReached:rows.length>=20000,
      openitiVersions:historic.length,wikidataWorks:wikidata.length,openitiWorks:openiti.length,
      added:result.additions.length,enriched:result.enriched,retiredSourceRows,retainedEditorialUpdates:retained.length,changed,installed,
      distinctSourceAuthors:new Set([...wikidata,...openiti].map(w=>w.auth)).size,
      newAuthors:[...new Set(result.additions.map(w=>w.auth))],
      byGenre:Object.fromEntries(['Fiction','Short Stories','Poetry','Drama','History','Biography','Philosophy','Science','Medicine','Linguistics','Religion'].map(g=>[g,result.additions.filter(w=>w.genres.includes(g)).length])),
      limitations:['Wikidata subset with Arabic language, title, named human author, book classification and pre-2022 publication evidence. Not all Arabic works.',
        'OpenITI author death years in AH are not publication years. Reuse thumbnails are not book covers.',
        'Metadata screening is not a full-text content or human-authorship certification.',
        'No Open Library bulk API harvesting or blocked-site bypass was used.']};
    fs.writeFileSync(path.join(cache,'import-report.json'),JSON.stringify(report,null,2));
    console.log(JSON.stringify({...report,newAuthors:report.newAuthors.slice(0,25)},null,2));
  } finally{release();}
}
if(require.main===module)main().catch(error=>{console.error(error);process.exitCode=1;});
module.exports={query};
