"use strict";

const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");

const ROOT = path.resolve(__dirname, "..");
const UPLOADS = path.join(ROOT, "uploads");
const OUTPUT = path.join(UPLOADS, "lorefy-catalog-map.js");
const PARTS = fs.readdirSync(UPLOADS)
  .map((name) => {
    const match = name.match(/^lorefy-data-part(\d+)\.js$/);
    return match ? Number(match[1]) : null;
  })
  .filter(Number.isInteger)
  .sort((a, b) => a - b);
const TYPE_ALIASES = new Map([
  ["Manga", "Manga"], ["\u0645\u0627\u0646\u062c\u0627", "Manga"],
  ["Manhwa", "Manhwa"], ["\u0645\u0627\u0646\u0647\u0648\u0627", "Manhwa"],
  ["Manhua", "Manhua"], ["\u0645\u0627\u0646\u0647\u0648\u0627 \u0635\u064a\u0646\u064a", "Manhua"], ["\u0645\u0627\u0646\u0647\u0648\u0627 \u0635\u064a\u0646\u064a\u0629", "Manhua"],
  ["Comics", "Comics"], ["\u0643\u0648\u0645\u064a\u0643\u0633", "Comics"],
  ["Novel", "Novel"], ["\u0631\u0648\u0627\u064a\u0629", "Novel"],
  ["Book", "Book"], ["\u0643\u062a\u0627\u0628", "Book"],
  ["Light Novel", "Light Novel"], ["\u0644\u0627\u064a\u062a \u0646\u0648\u0641\u0644", "Light Novel"],
  ["Web Novel", "Web Novel"], ["\u0648\u064a\u0628 \u0646\u0648\u0641\u0644", "Web Novel"]
]);

function normalizeType(value) {
  const text = String(value || "").trim();
  if (text.includes("\u0635\u064a\u0646\u064a")) return "Manhua";
  return TYPE_ALIASES.get(text) || "Manga";
}

function readPart(part) {
  const file = path.join(UPLOADS, `lorefy-data-part${String(part).padStart(2, "0")}.js`);
  const context = { window: { LorefyMangaData: [] }, Array };
  vm.runInNewContext(fs.readFileSync(file, "utf8"), context, { filename: file });
  return context.window.LorefyMangaData;
}

const manifest = {
  schema: 1,
  generatedAt: new Date().toISOString(),
  partCount: PARTS.length ? PARTS[PARTS.length - 1] : 0,
  featuredParts: [5],
  types: {},
  partSizes: {},
  workParts: {}
};

for (const part of PARTS) {
  const works = readPart(part);
  manifest.partSizes[part] = works.length;
  const seenTypes = new Set();
  for (const work of works) {
    if (!work || !work.id) continue;
    manifest.workParts[String(work.id)] = part;
    seenTypes.add(normalizeType(work.type));
  }
  for (const type of seenTypes) {
    if (!manifest.types[type]) manifest.types[type] = [];
    manifest.types[type].push(part);
  }
}

const source = `/* Generated by tools/build-catalog-map.js. */\nwindow.LorefyCatalogManifest=${JSON.stringify(manifest)};\n`;
fs.writeFileSync(OUTPUT, source, "utf8");
process.stdout.write(`${OUTPUT}\n${Object.keys(manifest.workParts).length} works indexed\n`);
