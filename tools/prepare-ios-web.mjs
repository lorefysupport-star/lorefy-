import { cp, mkdir, readFile, rm, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { execFileSync } from "node:child_process";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
execFileSync(process.execPath, [path.join(root, "tools", "build-runtime-catalog.js")], { stdio: "inherit" });
execFileSync(process.execPath, [path.join(root, "tools", "build-catalog-search-index.mjs")], { stdio: "inherit" });
const output = path.join(root, "ios-web");
const releaseConfigPath = path.join(root, "config", "lorefy-release.json");
const publicBuildConfigPath = path.join(root, "config", "lorefy-build-public.json");
const appConfigPath = path.join(root, "app.json");
const runtimeEntries = [
  "assets",
  "auth",
  "backend",
  "config",
  "launch",
  "modules",
  "monitoring",
  "styles",
  "uploads",
  "vendor",
  "index.html",
  "manifest.webmanifest",
  "privacy-policy.html",
  "support.html",
  "terms.html",
  "community-guidelines.html",
  "sw.js"
];

async function sourceExists(entry) {
  try {
    await stat(path.join(root, entry));
    return true;
  } catch {
    return false;
  }
}

const missing = [];
for (const entry of runtimeEntries) {
  if (!(await sourceExists(entry))) missing.push(entry);
}
if (missing.length) {
  throw new Error(`Cannot prepare the iOS web bundle. Missing: ${missing.join(", ")}`);
}

await rm(output, { recursive: true, force: true });
await mkdir(output, { recursive: true });
for (const entry of runtimeEntries) {
  await cp(path.join(root, entry), path.join(output, entry), { recursive: true });
}
const expansionFiles = [
  "manifest.json", "manga.json", "manhwa.json", "manhua.json", "comics.json",
  "novel.json", "book.json", "light-novel.json", "web-novel.json"
];
const expansionTarget = path.join(output, "output", "api-catalog");
await mkdir(expansionTarget, { recursive: true });
for (const file of expansionFiles) {
  await cp(path.join(root, "output", "api-catalog", file), path.join(expansionTarget, file));
}
// Local timing instrumentation is opt-in and never ships in normal builds.
await rm(path.join(output, "monitoring", "lorefy-performance-local.js"), { force: true });
// The editable release JSON may exist locally and must never ship verbatim.
await rm(path.join(output, "config", "lorefy-release.json"), { force: true });

async function readOptionalConfig(configPath, label) {
  try {
    return JSON.parse(await readFile(configPath, "utf8"));
  } catch (error) {
    if (error.code === "ENOENT") return {};
    throw new Error(`Invalid ${label} configuration: ${error.message}`);
  }
}

// EAS receives the checked-in public config. A local release config may
// override it, while remaining ignored because it can contain private notes.
const publicBuild = await readOptionalConfig(publicBuildConfigPath, "public build");
const localRelease = await readOptionalConfig(releaseConfigPath, "release");
const release = { ...publicBuild, ...localRelease };

let nativeRelease = {};
let nativeBuildNumber = "";
let nativeVersion = "";
try {
  const appConfig = JSON.parse(await readFile(appConfigPath, "utf8"));
  nativeRelease = appConfig?.expo?.extra?.lorefy || {};
  nativeBuildNumber = String(appConfig?.expo?.ios?.buildNumber || "");
  nativeVersion = String(appConfig?.expo?.version || "");
} catch (error) {
  throw new Error(`Invalid app configuration: ${error.message}`);
}

// Only browser-safe configuration is emitted into the native web bundle.
const runtime = {
  appUrl: typeof release.appUrl === "string" ? release.appUrl : "",
  apiUrl: typeof release.apiUrl === "string" ? release.apiUrl : "",
  catalogProxyUrl: typeof release.catalogProxyUrl === "string" ? release.catalogProxyUrl : "",
  appleBundleId: typeof release.appleBundleId === "string" ? release.appleBundleId : "com.lorefy.app",
  appleServiceId: typeof release.appleServiceId === "string" ? release.appleServiceId : "com.lorefy.app",
  buildNumber: nativeBuildNumber,
  appVersion: nativeVersion,
  betaGuestMode: nativeRelease.releaseMode === "beta" && nativeRelease.guestMode === true,
  betaPremiumUnlocked: nativeRelease.releaseMode === "beta" && nativeRelease.premiumUnlocked === true,
  betaProfileDecorations: nativeRelease.releaseMode === "beta" && nativeRelease.profileDecorations === true,
  nativeAppleSignInEnabled: nativeRelease.appleSignInEnabled === true,
  rightsSafeMedia: nativeRelease.rightsSafeMedia === true
};
if (typeof release.supabaseUrl === "string" && typeof release.supabasePublishableKey === "string") {
  runtime.supabase = { url: release.supabaseUrl, anonKey: release.supabasePublishableKey };
}
const runtimeScript = [
  "/* Generated by tools/prepare-ios-web.mjs. Do not add server secrets here. */",
  `window.LOREFY_RELEASE = ${JSON.stringify(runtime)};`,
  "window.LOREFY_SUPABASE = window.LOREFY_SUPABASE || window.LOREFY_RELEASE.supabase || null;",
  "window.LOREFY_BUILD_NUMBER = window.LOREFY_RELEASE.buildNumber || '';",
  // Keep runtime-only safeguards from the source template after injecting the
  // public release configuration. The template has no server secrets.
  await readFile(path.join(root, "config", "lorefy-runtime.js"), "utf8")
].join("\n");
await writeFile(path.join(output, "config", "lorefy-runtime.js"), `${runtimeScript}\n`, "utf8");

console.log(`Prepared ${runtimeEntries.length} Lorefy runtime entries in ios-web.`);
