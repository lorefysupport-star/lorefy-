'use strict';
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '..');

function compact(records) {
  const entries = Object.entries(records), groups = new Map(), recordGroups = new Map();
  for (const [id, record] of entries) {
    if (!record || typeof record !== 'object' || Array.isArray(record)) throw new Error('Unsupported chapter metadata record: ' + id);
    for (const [key, value] of Object.entries(record)) {
      if (key === '__proto__' || !((typeof value === 'string') || (typeof value === 'number' && Number.isFinite(value)))) {
        throw new Error('Unsupported chapter metadata field: ' + id + '.' + key);
      }
      if (key === 'sourceUrl' && typeof value !== 'string') throw new Error('Unsupported chapter metadata URL: ' + id);
    }
    if (id === '__proto__') throw new Error('Unsupported chapter metadata ID');
    const signature = JSON.stringify([Object.keys(record), Object.entries(record).filter(([key, value]) => key !== 'sourceUrl' && typeof value !== 'number')]);
    if (!groups.has(signature)) groups.set(signature, {index: groups.size, rows: []});
    const group = groups.get(signature);
    group.rows.push(record); recordGroups.set(id, group);
  }
  const numberOrString = value => Object.is(value, -0) ? '-0' : JSON.stringify(value);
  const factories = [];
  for (const group of groups.values()) {
    const first = group.rows[0], keys = Object.keys(first);
    const sharedCount = typeof first.chapters === 'number' && typeof first.latestChapter === 'number' &&
      group.rows.every(record => Object.is(record.chapters, record.latestChapter));
    group.params = keys.filter(key => (typeof first[key] === 'number' || key === 'sourceUrl') && !(key === 'latestChapter' && sharedCount));
    group.prefix = first.sourceUrl || '';
    for (const record of group.rows) while (!String(record.sourceUrl || '').startsWith(group.prefix)) group.prefix = group.prefix.slice(0, -1);
    const fields = keys.map(key => {
      const param = group.params.indexOf(key);
      let value;
      if (param >= 0) value = (key === 'sourceUrl' ? JSON.stringify(group.prefix) + '+' : '') + 'p' + param;
      else if (key === 'latestChapter' && sharedCount) value = 'p' + group.params.indexOf('chapters');
      else value = numberOrString(first[key]);
      return JSON.stringify(key) + ':' + value;
    });
    factories.push('function c' + group.index + '(' + group.params.map((_, index) => 'p' + index).join(',') + '){return{' + fields.join(',') + '}}');
  }
  // Emit records in their original order; factories share constants, never objects.
  const items = entries.map(([id, record]) => {
    const group = recordGroups.get(id);
    const args = group.params.map(key => numberOrString(key === 'sourceUrl' ? record[key].slice(group.prefix.length) : record[key]));
    return JSON.stringify(id) + ':c' + group.index + '(' + args.join(',') + ')';
  });
  return '/* Generated by tools/build-chapter-runtime.js; canonical metadata stays in lorefy-chapter-overrides.js. */\n' +
    '(function(){' + factories.join('') + 'window.LorefyChapterData=Object.assign(window.LorefyChapterData||{},{' + items.join(',') + '});})();\n';
}

function build() {
  const source = fs.readFileSync(path.join(root, 'uploads/lorefy-chapter-overrides.js'), 'utf8');
  const window = {};
  vm.runInNewContext(source, {window}, {timeout: 10000});
  if (!window.LorefyChapterData || typeof window.LorefyChapterData !== 'object') throw new Error('Missing canonical chapter metadata');
  const runtime = compact(window.LorefyChapterData);
  if (Buffer.byteLength(runtime) >= 240 * 1024) throw new Error('Chapter runtime exceeds startup budget');
  fs.writeFileSync(path.join(root, 'uploads/lorefy-chapter-runtime.js'), runtime);
  return {entries: Object.keys(window.LorefyChapterData).length, sourceBytes: Buffer.byteLength(source), runtimeBytes: Buffer.byteLength(runtime)};
}
if (require.main === module) console.log(build());
module.exports = {compact, build};
