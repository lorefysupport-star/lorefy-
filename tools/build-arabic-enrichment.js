'use strict';
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const crypto = require('node:crypto');
const factory = require('../modules/lorefy-arabic-enrichment-loader');
const root = path.resolve(__dirname, '..');

function build() {
  const source = fs.readFileSync(path.join(root, 'uploads/lorefy-ar-enrichment.js'), 'utf8');
  const context = {};
  vm.runInNewContext(source, context, {timeout: 10000});
  const entries = context.LorefyArabicEnrichment;
  if (!entries || typeof entries !== 'object') throw new Error('Missing Arabic source map');
  const buckets = Array.from({length: 256}, () => ({}));
  const {bucketForId} = factory({}, {});
  for (const id of Object.keys(entries).sort()) buckets[parseInt(bucketForId(id), 16)][id] = entries[id];
  const payloads = buckets.map(value => JSON.stringify(value));
  const contentHash = crypto.createHash('sha256').update(payloads.join('\n')).digest('hex').slice(0, 16);
  const dir = path.join(root, 'uploads/arabic-enrichment');
  fs.mkdirSync(dir, {recursive: true});
  for (let index = 0; index < payloads.length; index++) {
    if (Buffer.byteLength(payloads[index]) >= 64 * 1024) throw new Error('Synopsis bucket exceeds decode budget');
    fs.writeFileSync(path.join(dir, index.toString(16).padStart(2, '0') + '.json'), payloads[index]);
  }
  const manifest = {schema: 1, buckets: 256, contentHash, meta: context.LorefyArabicEnrichmentMeta};
  fs.writeFileSync(path.join(dir, 'manifest.js'), '/* Generated by tools/build-arabic-enrichment.js. */\nwindow.LorefyArabicEnrichmentRuntime=' + JSON.stringify(manifest) + ';\n');
  return {entries: Object.keys(entries).length, buckets: payloads.length, sourceBytes: Buffer.byteLength(source), maxShardBytes: Math.max(...payloads.map(value => Buffer.byteLength(value))), contentHash};
}
if (require.main === module) console.log(build());
module.exports = {build};
